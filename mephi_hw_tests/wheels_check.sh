#!/usr/bin/env bash
# =============================================================================
# Интерактивная проверка гусениц на приподнятом роботе.
#
# Каждый тест стартует только по Enter — можно спокойно встать у робота и
# смотреть. Команды идут через twist_mux, тем же путём, что пойдёт от геймпада.
#
#   bash wheels_check.sh            # с ноутбука: make wheels
# =============================================================================
# Без set -u: setup.bash ROS обращается к незаданным переменным и падает с ним.
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source /opt/ros/humble/setup.bash
export ROS_DOMAIN_ID="${ROS_DOMAIN_ID:-42}"

run_step() {
  local title="$1" watch="$2"
  shift 2
  echo
  echo "================================================================"
  echo " $title"
  echo "================================================================"
  echo "$watch"
  echo
  while true; do
    read -rp "Enter — запустить,  s — пропустить,  q — выйти: " ans
    case "$ans" in
      q|Q) echo "Выход."; exit 0 ;;
      s|S) return ;;
    esac
    python3 "$HERE/drive_test.py" "$@"
    echo
    read -rp "Повторить этот тест? [y/N]: " again
    [[ "$again" =~ ^[yYдД] ]] || return
  done
}

echo "Проверка гусениц. Робот должен стоять приподнятым: гусеницы крутятся в воздухе."
echo "Одна из гусениц может рвануть на полную скорость — это известная неисправность,"
echo "ради поиска которой и идёт тест. После «СТОП» обе должны остановиться."

run_step "ТЕСТ 1: ВПЕРЁД, медленно, 6 секунд" \
"Смотрите на обе гусеницы (лево/право — если стоять позади робота):
  - какая крутится быстро, какая медленно;
  - в какую сторону крутится каждая: так, чтобы робот ехал ВПЕРЁД или НАЗАД?" \
  --vx 0.05 --dur 6 --countdown 3

run_step "ТЕСТ 2: РАЗВОРОТ НА МЕСТЕ ВЛЕВО, 6 секунд" \
"Задумано так: левая гусеница назад, правая вперёд.
Смотрите: какая гусеница сменила направление по сравнению с тестом 1?" \
  --wz 0.6 --dur 6 --countdown 3

echo
echo "Готово. Напишите в чат, что видели."
